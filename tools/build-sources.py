#!/usr/bin/env python3
"""Regenerates content/sources.json from the source PDF.

    python3 -I tools/build-sources.py "<path to the PDF>" > content/sources.json

The PDF is git-ignored (D14), so this is run locally by whoever holds it. It needs
`pypdf` (a dev-time tool only; nothing here ships to the site).

What is *derived* — every URL, which page each pill sits on, the counts — is read
from the PDF's own link annotations and paired with the printed pills by page and
reading order. What is *judged* — each domain's name, tier and rationale, and the
sources the document names without linking — lives in tools/source-meta.json,
where it can be reviewed and edited by hand. Nothing is patched into the output
afterwards, so re-running this reproduces the committed file exactly.
"""
import collections
import json
import pathlib
import re
import sys
from urllib.parse import urlparse

from pypdf import PdfReader

HERE = pathlib.Path(__file__).resolve().parent
META = json.loads((HERE / "source-meta.json").read_text(encoding="utf-8"),
                  object_pairs_hook=collections.OrderedDict)
MARKERS = set(META["domains"])

reader = PdfReader(sys.argv[1])

# Link annotations per page, in reading order (top to bottom, then left to right).
annots = collections.defaultdict(list)
for number, page in enumerate(reader.pages, 1):
    for annotation in page.get("/Annots", []) or []:
        try:
            obj = annotation.get_object()
        except Exception:
            continue
        uri = (obj.get("/A") or {}).get("/URI")
        if uri:
            rect = [float(x) for x in obj.get("/Rect", [0, 0, 0, 0])]
            annots[number].append((rect, str(uri)))
for number in annots:
    annots[number].sort(key=lambda item: (-round(item[0][3], 1), item[0][0]))

# Printed pills per page, in the same order. An overflow pill prints `cgiar +3`.
pills = collections.defaultdict(list)
for number, page in enumerate(reader.pages, 1):
    for line in (page.extract_text() or "").split("\n"):
        text = line.strip()
        marker = re.sub(r" \+\d+$", "", text)
        if marker in MARKERS:
            overflow = re.search(r"\+(\d+)$", text)
            pills[number].append((marker, int(overflow.group(1)) if overflow else 0))

occurrences = []
for number in sorted(set(annots) | set(pills)):
    assert len(annots[number]) == len(pills[number]), f"p{number}: annotations and pills disagree"
    for index, ((_, uri), (marker, more)) in enumerate(zip(annots[number], pills[number])):
        host = urlparse(uri).netloc.lower().removeprefix("www.").replace("-", "")
        # The cross-check that makes the pairing evidence rather than assumption.
        assert marker.split("-")[0][:4] in host or marker in host, (number, marker, uri)
        occurrences.append((number, index, marker, more, uri))

documents = collections.OrderedDict()
slots = collections.OrderedDict()
domains = collections.OrderedDict()
hidden = []
for number, index, marker, more, uri in occurrences:
    m = META["domains"][marker]
    domain = domains.setdefault(marker, collections.OrderedDict(
        id=marker, name=m["name"], tier=m["tier"], rationale=m["rationale"],
        basis=m["basis"], documents=[]))
    if uri not in domain["documents"]:
        domain["documents"].append(uri)
    documents.setdefault(uri, []).append(number)
    slots.setdefault(uri, []).append(collections.OrderedDict(page=number, index=index))
    if more:
        hidden.append(collections.OrderedDict(anchoredTo=marker, page=number, hiddenSources=more))

missing = set(META["domains"]) - set(domains)
assert not missing, f"metadata describes domains the PDF does not cite: {sorted(missing)}"

output = collections.OrderedDict(
    **{"$comment": (
        "Generated by tools/build-sources.py from the PDF's own link annotations, paired with their "
        "pills by page and reading order (all 67 agree by domain). Judgements — names, tiers, "
        "rationales, named-only sources — come from tools/source-meta.json. Tiers are this "
        "project's reading of D9 and are listed for owner review in docs/content/TIER-REVIEW.md. "
        "`basis` records how a tier was reached: `domain` means the host itself decides it; "
        "`inferred-from-url` means only the URL was inspected. No site was fetched to make a tier.")},
    pillCensus=collections.OrderedDict(
        pills=len(occurrences), documents=len(documents), domains=len(domains),
        hiddenBehindOverflow=sum(h["hiddenSources"] for h in hidden)),
    tiers=META["tiers"],
    domains=sorted(domains.values(), key=lambda d: d["id"]),
    documents=[collections.OrderedDict(
        url=url, domain=next(k for k, v in domains.items() if url in v["documents"]), pages=pages,
        occurrences=slots[url])
        for url, pages in documents.items()],
    unresolvedOverflow=[collections.OrderedDict(
        h, note="The pill prints a count, not names; no link annotation exists for these.")
        for h in hidden],
    namedOnly=META["namedOnly"],
)
print(json.dumps(output, indent=2, ensure_ascii=False))
